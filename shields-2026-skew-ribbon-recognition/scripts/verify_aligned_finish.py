r"""Paper section `sec:children` (Actual children and recovery from the two boundary words),
ge:aligned-finish, first paragraph (the aligned lift).

J = A_J o_kappa K is an actual proper chart with kappa of period d >= 2, and mu is a legal mark on
J of period r with d dividing r.  For every connected outer V the lemma gives

    V o_mu J = (gamma(V) o_lambda A_J) o_kappa K

with an actual legal mark lambda on A_J and gamma in {id, AT}, gamma = id unless lambda is empty,
the same (lambda, gamma) serving every outer.  The charts of J are generated by composition from
every connected K of at most K_CELLS cells and A_J of at most A_CELLS cells; for each chart and each
mu the check searches the legal marks lambda of A_J and both gauges for one that works for all
connected V of at least one cell and at most OUTER cells simultaneously, and asserts that one exists
and respects the gauge restriction.  Both equalities are computed by the gluing composition.

The remaining paragraphs of the lemma (the contradiction with a held minimum and the whole-parent
conclusion) involve Schur-function equalities of whole parents and are not checked here.
"""
from _gluing_common import antitranspose, compose
from check_two_copy_flags import diagrams, marks

K_CELLS = 5
A_CELLS = 6
OUTER = 4
J_LIMIT = 12


def main():
    outers = list(diagrams(OUTER)) + [frozenset({(0, 0)})]
    charts = {}
    for K in diagrams(K_CELLS):
        for kap in marks(K):
            if kap.period < 2:
                continue
            for A in diagrams(A_CELLS):
                J = compose(A, kap)
                if len(J) <= J_LIMIT:
                    charts.setdefault(J, []).append((A, kap))
    total = nonempty_lambda = 0
    for J, lst in charts.items():
        for mu in marks(J):
            for A, kap in lst:
                if mu.period % kap.period:
                    continue
                survivors = None
                for V in outers:
                    target = compose(V, mu)
                    good = set()
                    for i, lam in enumerate(marks(A)):
                        for gamma in ('id', 'AT'):
                            if gamma == 'AT' and lam.lower:
                                continue
                            Vg = V if gamma == 'id' else antitranspose(V)
                            if compose(compose(Vg, lam), kap) == target:
                                good.add((i, gamma))
                    survivors = good if survivors is None else survivors & good
                assert survivors, (sorted(J), mu.case, mu.period, kap.period)
                total += 1
                nonempty_lambda += any(list(marks(A))[i].lower for i, _ in survivors)
    assert total > 0 and nonempty_lambda > 0
    print(f'ge:aligned-finish: {total} (chart, mark) pairs over {len(charts)} diagrams J; a common '
          f'(lambda, gamma) with gamma = id unless lambda is empty exists for all outers; '
          f'{nonempty_lambda} with a positive lambda')
    print('ALL PASS')


if __name__ == '__main__':
    main()
