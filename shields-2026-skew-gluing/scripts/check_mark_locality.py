#!/usr/bin/env python3
"""Window locality of legal marks and transfer across equal-span outers.

Checks, on finite ranges, the mixed-case translate in item (3) of
lem:gluing-local, the locality lemma for legality (lem:gluing-mark-locality)
and the equal-span transfer corollary (cor:gluing-mark-transfer), with the two
witnesses printed after them.

Legality is decided by the cell-set predicate of verify_common_factor_graphs,
which reads the whole diagram, so nothing here assumes the locality under test.
The mark lister built on it is first compared with the separate mark search of
check_gcd_fold_sweep.  Connected diagrams are generated by area from row
profiles and by span from boundary bit words; the span generator is checked
against the Catalan counts and, for small spans, against the area generator.

Firing controls: windows narrowed by one diagonal at either end must split some
class; at width q no mixed composite carries a legal mark while some ordinary
composite does, and width q + 1 must split some equal-span class; a literal comparison across equal-span outers must fail for
ordinary marks, whose last window moves with the outer's row count.

Usage: check_mark_locality.py [--full]
"""
from __future__ import annotations

import argparse
from collections import defaultdict
from itertools import product

import check_gcd_fold_sweep as R
import verify_common_factor_graphs as V

shift, content, normalize, span = V.shift, V.content, V.normalize, V.span
southwest, northeast, skew = V.southwest, V.northeast, V.is_connected_skew

CASES = {(True, True): 'a', (False, False): 'b', (True, False): 'c', (False, True): 'd'}


def legal_marks(E, widths=None):
    """Every legal nonempty mark of the southwest-normalized diagram E.

    Candidates are the full intersections E & (E - x) for the cells x of
    content q = N - w; the attachment case is read from the cells, and the
    whole-diagram predicate V.legal decides I--IV.
    """
    E = normalize(E)
    N = span(E)
    marks = []
    for w in range(1, (N + 1) // 2):
        if widths is not None and w not in widths:
            continue
        q = N - w
        for x in E:
            if content(x) != q:
                continue
            W = E & shift(E, (-x[0], -x[1]))
            T = shift(W, x)
            if (0, 0) not in W or northeast(E) not in T or span(W) != w or not skew(W):
                continue
            O = E - W - T
            if not skew(O):
                continue
            i, j = southwest(O)
            k, l = northeast(O)
            case = CASES[(i, j - 1) in W, (k, l + 1) in T]
            mark = V.Mark(E, W, T, case, x)
            if V.legal(mark):
                marks.append(mark)
    return marks


def hatted_mark(mark):
    """The hatted set of W_-; at its contents only E and E - v meet the amalgamation."""
    E, W, x = mark.inner, mark.lower, mark.displacement
    local = E | shift(E, (-x[0], -x[1]))
    return frozenset({y for y in local if (y[0] + 1, y[1] + 1) in W}
                     | {y for y in W if (y[0] + 1, y[1] + 1) in local})


def window(E, low, high, anchor):
    cells = frozenset(c for c in E if low <= content(c) <= high)
    return shift(cells, (-anchor[0], -anchor[1]))


def shapes_by_area(n):
    for k in range(1, n + 1):
        for S in R.shapes(k):
            yield normalize(S)


def shapes_by_span(M):
    """All connected diagrams of span M, from their two boundary bit words."""
    found = set()
    for A in product((0, 1), repeat=M - 1):
        for B in product((0, 1), repeat=M - 1):
            S = R.from_bits(A, B)
            if S is not None:
                found.add(normalize(S))
    return sorted(found, key=lambda S: (len(S), sorted(S)))


def check_instruments(max_area):
    """The lister against check_gcd_fold_sweep's search; the two diagram generators."""
    marks = 0
    for E in shapes_by_area(max_area):
        if len(E) < 3:
            continue
        mine = {(m.lower, m.displacement, m.case) for m in legal_marks(E)}
        s = R.endpoints(E)[0]
        theirs = {(shift(m.W, (-s[0], -s[1])), m.v, m.case) for m in R.marks(E) if m.W}
        assert mine == theirs, sorted(E)
        marks += len(mine)
    catalan = [1, 1, 2, 5, 14, 42, 132, 429]
    for M in range(1, 7):
        shapes = shapes_by_span(M)
        assert len(shapes) == catalan[M], M
        assert all(skew(S) and span(S) == M for S in shapes)
        if M <= 3:
            by_area = {S for S in shapes_by_area(2 * M) if span(S) == M}
            assert by_area <= set(shapes)
    # A lister that keeps every full-intersection candidate with connected skew
    # complements, without testing I and IV, must admit extra marks.
    loose = 0
    for E in shapes_by_area(max_area):
        if len(E) < 3:
            continue
        N = span(E)
        for w in range(1, (N + 1) // 2):
            for x in E:
                if content(x) != N - w:
                    continue
                W = E & shift(E, (-x[0], -x[1]))
                T = shift(W, x)
                if (0, 0) in W and northeast(E) in T and span(W) == w and skew(W):
                    O = E - W - T
                    if all(skew(S) for S in (O, E - W, E - T)):
                        i, j = southwest(O)
                        k, l = northeast(O)
                        mark = V.Mark(E, W, T, CASES[(i, j - 1) in W, (k, l + 1) in T], x)
                        loose += not V.legal(mark)
    assert loose, "a lister without Hypotheses I and IV should admit extra marks"
    print(f"instruments: {marks} legal nonempty marks on every connected diagram of area 3 to "
          f"{max_area} agree with the separate search; spans 1 to 6 give the Catalan counts; "
          f"dropping I and IV admits {loose} extra candidates (control fires)")


def cell_criterion(S):
    """The cell-set form of the diagonal criterion, clause by clause."""
    diagonals = defaultdict(list)
    for i, j in S:
        diagonals[j - i].append(i)
    if not diagonals:
        return False
    ks = sorted(diagonals)
    if ks != list(range(ks[0], ks[-1] + 1)):
        return False
    rows = {k: sorted(diagonals[k]) for k in ks}
    if any(r != list(range(r[0], r[-1] + 1)) for r in rows.values()):
        return False
    if any(rows[k - 1][0] - rows[k][0] not in (0, 1) or rows[k - 1][-1] - rows[k][-1] not in (0, 1)
           for k in ks[1:]):
        return False
    return len(rows[ks[0]]) == 1 and len(rows[ks[-1]]) == 1


def check_cell_criterion(height=4, width=4):
    """Diagonal geometry: the cell-set criterion equals the row-interval predicate on
    every subset of a box, and each cell off the last diagonal has its eastern or
    northern neighbor on the next one.  Control: without the singleton-end clause
    the two predicates disagree."""
    box = [(i, j) for i in range(height) for j in range(width)]
    accepted = loose = 0
    for m in range(1, 1 << len(box)):
        S = frozenset(box[b] for b in range(len(box)) if m >> b & 1)
        verdict = cell_criterion(S)
        assert verdict == skew(S), sorted(S)
        if verdict:
            accepted += 1
            top = max(map(content, S))
            assert all((i, j + 1) in S or (i - 1, j) in S for i, j in S if j - i < top), sorted(S)
        diagonals = defaultdict(list)
        for i, j in S:
            diagonals[j - i].append(i)
        ks = sorted(diagonals)
        no_ends = (ks == list(range(ks[0], ks[-1] + 1))
                   and all(sorted(r) == list(range(min(r), max(r) + 1)) for r in diagonals.values())
                   and all(min(diagonals[k - 1]) - min(diagonals[k]) in (0, 1)
                           and max(diagonals[k - 1]) - max(diagonals[k]) in (0, 1) for k in ks[1:]))
        loose += no_ends != skew(S)
    assert loose, "dropping the singleton-end clause should change the verdict"
    print(f"cell-set criterion: {(1 << len(box)) - 1} subsets of a {height}x{width} box agree with the "
          f"row-interval predicate ({accepted} connected skew); without singleton ends {loose} differ "
          f"(control fires)")


def check_southeast_word(mark, outer, E):
    """lem:gluing-coding, case (d): h_F(qj + a) = h_E(a) + j v_1 on every diagonal, so the
    southeast word is q-periodic with no exceptional residue; case (c) is the northwest mirror."""
    q, v = mark.period, mark.displacement
    J = mark.inner
    def ends(S, pick):
        d = defaultdict(list)
        for i, j in S:
            d[j - i].append(i)
        return {k: pick(r) for k, r in d.items()}
    pick = max if mark.case == 'd' else min
    hE, hJ = ends(E, pick), ends(J, pick)
    N = span(E)
    for k in range(N):
        j, a = divmod(k, q)
        assert hE[k] == hJ[a] + j * v[0], (mark.case, sorted(outer), k)
    word = [hE[k - 1] - hE[k] for k in range(1, N)]
    assert all(word[k] == word[k + q] for k in range(len(word) - q))


def check_window_translate(max_inner, max_span):
    """lem:gluing-local (3): a mixed composite's last window is translated by (r - 1)v."""
    outers = {M: shapes_by_span(M) for M in range(2, max_span + 1)}
    composites = ordinary_moved = 0
    for J in shapes_by_area(max_inner):
        if len(J) < 3:
            continue
        for mu in legal_marks(J):
            q, u, v = mu.period, mu.width, mu.displacement
            for M, Vs in outers.items():
                N = M * q + u
                literal = set()
                for D in Vs:
                    E = V.compose(D, mu)
                    assert E == V.compose_by_offsets(D, mu) and span(E) == N
                    first = window(E, 0, q - 1, (0, 0))
                    last = window(E, N - q, N - 1, (0, 0))
                    assert first == window(J, 0, q - 1, (0, 0))
                    translate = ((M - 1) * v[0], (M - 1) * v[1])
                    if mu.case in 'cd':
                        assert last == shift(window(J, u, q + u - 1, (0, 0)), translate)
                        check_southeast_word(mu, D, E)
                        composites += 1
                    else:
                        literal.add(last)
                        # The ordinary last window is still a translate, by a vector
                        # that moves with the outer.
                        ne = northeast(E)
                        assert window(E, N - q, N - 1, ne) == window(J, u, q + u - 1, northeast(J))
                ordinary_moved += len(literal) > 1
    assert ordinary_moved, "the ordinary control should see the last window move"
    print(f"window translate: {composites} mixed composites have last window translated by "
          f"(r-1)v; ordinary control moves on {ordinary_moved} (mark, span) classes")


def check_locality(max_area):
    """lem:gluing-mark-locality on every connected diagram of bounded area."""
    full = defaultdict(set)
    narrow = {'southwest': defaultdict(set), 'northeast': defaultdict(set),
              'both': defaultdict(set)}
    pairs = 0
    for E in shapes_by_area(max_area):
        N = span(E)
        if N < 3:
            continue
        marks = legal_marks(E)
        ne = northeast(E)
        for w in range(1, (N + 1) // 2):
            pairs += 1
            data = frozenset((m.lower, shift(m.upper, (-ne[0], -ne[1])), m.case, hatted_mark(m))
                             for m in marks if m.width == w)
            sw_full, sw_narrow = window(E, 0, w, (0, 0)), window(E, 0, w - 1, (0, 0))
            ne_full, ne_narrow = window(E, N - w - 1, N - 1, ne), window(E, N - w, N - 1, ne)
            full[N, w, sw_full, ne_full].add(data)
            narrow['southwest'][N, w, sw_narrow, ne_full].add(data)
            narrow['northeast'][N, w, sw_full, ne_narrow].add(data)
            narrow['both'][N, w, sw_narrow, ne_narrow].add(data)
    shared = sum(1 for d in full.values() if d)
    split = sum(len(d) > 1 for d in full.values())
    assert split == 0, "legality is not determined by the two windows"
    fired = {name: sum(len(d) > 1 for d in groups.values()) for name, groups in narrow.items()}
    assert all(fired.values()), fired
    # The witness printed after the lemma.
    row, hook = V.from_profile((3,), ()), V.from_profile((2, 1), (0,))
    assert window(row, 0, 0, (0, 0)) == window(hook, 0, 0, (0, 0))
    assert window(row, 1, 2, northeast(row)) == window(hook, 1, 2, northeast(hook))
    assert [m.case for m in legal_marks(row, {1})] == ['a']
    assert [m.case for m in legal_marks(hook, {1})] == ['d']
    print(f"locality: {pairs} (diagram, width) pairs in {len(full)} window classes, none split; "
          f"narrowed windows split classes (control fires): {fired}; row/hook witness holds")


def check_transfer(max_inner, max_span):
    """cor:gluing-mark-transfer for every mixed mark and every outer of each span."""
    outers = {M: shapes_by_span(M) for M in range(2, max_span + 1)}
    constant = defaultdict(lambda: [0, 0])
    ordinary_split = 0
    width_q = {'mixed': 0, 'ordinary': 0}
    for J in shapes_by_area(max_inner):
        if len(J) < 3:
            continue
        for mu in legal_marks(J):
            q, u0 = mu.period, mu.width
            for M, Vs in outers.items():
                composites = [V.compose(D, mu) for D in Vs]
                N = M * q + u0
                for u in range(0, q + 2):
                    if not 2 * u < N:
                        continue
                    seen = set()
                    for E in composites:
                        if u == 0:
                            seen.add(northeast(E))
                        else:
                            found = legal_marks(E, {u})
                            if u == q:
                                width_q['ordinary' if mu.case in 'ab' else 'mixed'] += len(found)
                            seen.add(frozenset((m.lower, m.upper, m.case, m.displacement,
                                                hatted_mark(m)) for m in found))
                    if mu.case in 'ab':
                        ordinary_split += u < q and len(seen) > 1
                        continue
                    key = 'u<q' if u < q else f'u=q+{u - q}'
                    constant[key][0] += 1
                    constant[key][1] += len(seen) > 1
    assert constant['u<q'][0] and constant['u<q'][1] == 0, "transfer fails below the window size"
    assert constant['u=q+0'][0] and constant['u=q+0'][1] == 0, "transfer fails at width q"
    assert width_q['mixed'] == 0, "a mixed composite carries a legal mark of width q"
    assert width_q['ordinary'], "the ordinary width-q control should find a mark"
    assert constant['u=q+1'][1], "the width q + 1 control should split some class"
    assert ordinary_split, "the literal comparison should fail for some ordinary mark"
    # The sharpness witness printed after the corollary.
    hook = V.from_profile((2, 1), (0,))
    omega = V.singleton_mark(hook)
    assert (omega.case, omega.period, omega.width) == ('d', 2, 1)
    row, square = V.from_profile((3,), ()), V.from_profile((2, 2), (1,))
    assert span(row) == span(square) == 3
    assert len(legal_marks(V.compose(row, omega), {3})) == 1
    assert not legal_marks(V.compose(square, omega), {3})
    summary = {k: f"{v[1]} of {v[0]} split" for k, v in sorted(constant.items())}
    print(f"transfer: mixed marks, outers of span 2 to {max_span}: {summary}; ordinary literal "
          f"control splits {ordinary_split} classes; width-q marks: none on mixed composites, "
          f"{width_q['ordinary']} on ordinary ones (control fires); width-three witness holds")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--full', action='store_true')
    args = parser.parse_args()
    check_cell_criterion()
    if args.full:
        check_instruments(11)
        check_window_translate(10, 6)
        check_locality(16)
        check_transfer(10, 6)
    else:
        check_instruments(9)
        check_window_translate(8, 5)
        check_locality(13)
        check_transfer(8, 5)
    print("ALL PASS")


if __name__ == '__main__':
    main()
